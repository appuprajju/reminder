export function t(langCode: string | undefined | null, key: keyof UiTranslationPack): string {
  const opt = getLanguageOption(langCode);
  const pack = TRANSLATIONS[opt.id];
  return pack?.[key] || EN_BASE[key];
}

export function getLocalizedGreeting(date: Date, langCode?: string | null): string {
  const h = date.getHours();
  if (h < 12) return t(langCode, 'goodMorning');
  if (h < 17) return t(langCode, 'goodAfternoon');
  if (h < 21) return t(langCode, 'goodEvening');
  return t(langCode, 'goodNight');
}

export function formatLocalizedDate(date: Date, langCode?: string | null): string {
  const opt = getLanguageOption(langCode);
  try {
    return date.toLocaleDateString(opt.id, {
      weekday: 'long',
      month: 'short',
      day: 'numeric',
    });
  } catch {
    return date.toLocaleDateString('en-IN', {
      weekday: 'long',
      month: 'short',
      day: 'numeric',
    });
  }
}
